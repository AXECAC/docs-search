PUNCTUATION = {
    'en': r'[^\w\s]',
    'ru': r'[^\w\s\u0400-\u04FF]'  # Preserve Cyrillic characters
}

def get_stopwords(language: str = 'en'):
    """Get stopwords for the specified language."""
    return STOPWORDS.get(language, STOPWORDS['en'])

def get_punctuation_pattern(language: str = 'en'):
    """Get punctuation pattern for the specified language."""
    return PUNCTUATION.get(language, PUNCTUATION['en'])

# Дополнительная функция для проверки, является ли слово стоп-словом
def is_stopword(word: str, language: str = 'en') -> bool:
    """Check if a word is a stopword."""
    return word.lower() in get_stopwords(language)